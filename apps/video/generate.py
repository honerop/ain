#!/usr/bin/env python3
"""CLI plumbing for Ain's JSON video renderer.

The timeline, interpolation and SVG frames are generated by render.ain.
Python validates user input and connects Ain to the external rasterizer/encoder.
No Python graphics or animation libraries are required.
"""
from __future__ import annotations

import argparse
import base64
import copy
from concurrent.futures import ThreadPoolExecutor
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
RENDERER = Path(__file__).with_name("render.ain")
MAX_FRAMES = 18_000
COLOR = re.compile(r"(?:#[0-9a-fA-F]{3}|#[0-9a-fA-F]{6}|[A-Za-z]{1,32})\Z")
ANIMATED = {"x", "y", "width", "height", "cx", "cy", "r", "x1", "y1", "x2", "y2"}
GEOMETRY = {
    "rect": ("x", "y", "width", "height"),
    "circle": ("cx", "cy", "r"),
    "line": ("x1", "y1", "x2", "y2"),
    "text": ("x", "y", "value"),
    "image": ("x", "y", "width", "height"),
}


def integer(value: object, where: str, low: int, high: int) -> int:
    if type(value) is not int or not low <= value <= high:
        raise ValueError(f"{where} must be an integer from {low} to {high}")
    return value


def color(value: object, where: str) -> None:
    if not isinstance(value, str) or not COLOR.fullmatch(value):
        raise ValueError(f"{where} must be a named or hex color")


def validate(spec: object) -> tuple[int, int]:
    """Validate geometry and bounds before Ain starts allocating frame files."""
    if not isinstance(spec, dict):
        raise ValueError("project must be a JSON object")
    width = integer(spec.get("width"), "width", 2, 8192)
    height = integer(spec.get("height"), "height", 2, 8192)
    if width % 2 or height % 2:
        raise ValueError("width and height must be even for yuv420p video")
    fps = integer(spec.get("fps", 24), "fps", 1, 60)
    scenes = spec.get("scenes")
    if not isinstance(scenes, list) or not 1 <= len(scenes) <= 1000:
        raise ValueError("scenes must be a nonempty array (maximum 1000)")
    total = 0
    for si, scene in enumerate(scenes):
        prefix = f"scenes[{si}]"
        if not isinstance(scene, dict):
            raise ValueError(f"{prefix} must be an object")
        if "frames" in scene:
            frames = integer(scene["frames"], f"{prefix}.frames", 1, MAX_FRAMES)
        else:
            seconds = integer(scene.get("duration"), f"{prefix}.duration", 1, 600)
            frames = seconds * fps
        total += frames
        if total > MAX_FRAMES:
            raise ValueError(f"video exceeds {MAX_FRAMES} frames")
        color(scene.get("background", "#101825"), f"{prefix}.background")
        elements = scene.get("elements")
        if not isinstance(elements, list) or len(elements) > 999:
            raise ValueError(f"{prefix}.elements must be an array of up to 999 objects")
        for ei, shape in enumerate(elements):
            label = f"{prefix}.elements[{ei}]"
            if not isinstance(shape, dict):
                raise ValueError(f"{label} must be an object")
            kind = shape.get("kind")
            if not isinstance(kind, str) or kind not in GEOMETRY:
                raise ValueError(f"{label}.kind must be rect, circle, line, text or image")
            for field in GEOMETRY[kind]:
                if field == "value":
                    value = shape.get(field)
                    if not isinstance(value, str) or len(value.encode("utf-8")) > 10_000:
                        raise ValueError(f"{label}.value must be text up to 10000 bytes")
                else:
                    integer(shape.get(field), f"{label}.{field}", -32768, 32768)
            if kind == "image":
                path = shape.get("path")
                if not isinstance(path, str) or not path or path.startswith(("http:", "https:", "data:")):
                    raise ValueError(f"{label}.path must be a local image filename")
                if Path(path).suffix.lower() not in (".png", ".jpg", ".jpeg"):
                    raise ValueError(f"{label}.path must end in .png, .jpg or .jpeg")
            for field in ANIMATED & shape.keys():
                integer(shape[field], f"{label}.{field}", -32768, 32768)
            for key in ("from", "to"):
                if key in shape:
                    obj = shape[key]
                    if not isinstance(obj, dict) or set(obj) - ANIMATED:
                        raise ValueError(f"{label}.{key} must contain only animated geometry fields")
                    for field, value in obj.items():
                        integer(value, f"{label}.{key}.{field}", -32768, 32768)
            for size in ("width", "height", "r"):
                if size in shape:
                    integer(shape[size], f"{label}.{size}", 0, 32768)
                for key in ("from", "to"):
                    if size in shape.get(key, {}):
                        integer(shape[key][size], f"{label}.{key}.{size}", 0, 32768)
            if kind == "image":
                for field in ("width", "height"):
                    if shape[field] <= 0:
                        raise ValueError(f"{label}.{field} must be positive")
                    for phase in ("from", "to"):
                        if phase in shape and field in shape[phase] and shape[phase][field] <= 0:
                            raise ValueError(f"{label}.{phase}.{field} must be positive")
            for attr in ("fill", "stroke"):
                if attr in shape:
                    color(shape[attr], f"{label}.{attr}")
            if "stroke_width" in shape:
                integer(shape["stroke_width"], f"{label}.stroke_width", 1, 128)
            if "font_size" in shape:
                integer(shape["font_size"], f"{label}.font_size", 1, 512)
            if shape.get("anchor", "start") not in ("start", "middle", "end"):
                raise ValueError(f"{label}.anchor must be start, middle or end")
            if shape.get("ease", "linear") not in ("linear", "smooth"):
                raise ValueError(f"{label}.ease must be linear or smooth")
    for key in ("voiceover", "music"):
        if key in spec and not isinstance(spec[key], str):
            raise ValueError(f"{key} must be a local audio file path")
    return fps, total


def embed_images(spec: dict, project_path: Path) -> dict:
    """Replace local image paths with SVG-safe embedded PNG/JPEG data URIs."""
    result = copy.deepcopy(spec)
    for scene in result["scenes"]:
        for shape in scene["elements"]:
            if shape["kind"] != "image":
                continue
            filename = Path(shape.pop("path")).expanduser()
            if not filename.is_absolute():
                filename = project_path.parent / filename
            if not filename.is_file():
                raise ValueError(f"image file not found: {filename}")
            content = filename.read_bytes()
            if not content or len(content) > 1_000_000:
                raise ValueError(f"image must be 1..1000000 bytes: {filename}")
            if filename.suffix.lower() == ".png":
                if not content.startswith(b"\x89PNG\r\n\x1a\n"):
                    raise ValueError(f"invalid PNG header: {filename}")
                mimetype = "image/png"
            else:
                if not content.startswith(b"\xff\xd8\xff"):
                    raise ValueError(f"invalid JPEG header: {filename}")
                mimetype = "image/jpeg"
            shape["data"] = f"data:{mimetype};base64," + base64.b64encode(content).decode("ascii")
    return result


def rasterize(pair: tuple[Path, Path]) -> None:
    source, target = pair
    subprocess.run(["rsvg-convert", "--output", str(target), str(source)], check=True)


def audio_path(value: str | None, spec_path: Path) -> Path | None:
    if not value:
        return None
    path = Path(value).expanduser()
    if not path.is_absolute():
        path = spec_path.parent / path
    if not path.is_file():
        raise ValueError(f"audio file not found: {path}")
    return path.resolve()


def encode_video(
    frames: Path, output: Path, fps: int, total: int,
    voice: Path | None, music: Path | None,
) -> None:
    seconds = total / fps
    command = [
        "ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
        "-framerate", str(fps), "-i", str(frames / "frame_%06d.png"),
    ]
    if voice:
        command.extend(["-i", str(voice)])
    if music:
        command.extend(["-stream_loop", "-1", "-i", str(music)])
    command += ["-map", "0:v:0", "-c:v", "libx264", "-preset", "medium",
                "-crf", "18", "-pix_fmt", "yuv420p", "-frames:v", str(total)]
    if voice and music:
        command += [
            "-filter_complex",
            f"[1:a]volume=1,apad,atrim=duration={seconds:.6f}[v];"
            f"[2:a]volume=0.18,atrim=duration={seconds:.6f},apad[m];"
            f"[v][m]amix=inputs=2:duration=longest:dropout_transition=0,"
            f"atrim=duration={seconds:.6f}[a]",
            "-map", "[a]", "-c:a", "aac", "-b:a", "192k",
        ]
    elif voice or music:
        audio_input = "1:a"
        gain = "1" if voice else "0.18"
        command += [
            "-filter_complex", f"[{audio_input}]volume={gain},apad,"
            f"atrim=duration={seconds:.6f}[a]",
            "-map", "[a]", "-c:a", "aac", "-b:a", "192k",
        ]
    command += ["-t", f"{seconds:.6f}", "-movflags", "+faststart", str(output)]
    subprocess.run(command, check=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate an MP4 from animated JSON using Ain")
    parser.add_argument("project", type=Path, help="JSON project")
    parser.add_argument("output", type=Path, help="MP4 output")
    parser.add_argument("--voiceover", type=str, help="narration file (overrides JSON)")
    parser.add_argument("--music", type=str, help="music file (overrides JSON)")
    parser.add_argument("--keep-frames", action="store_true", help="copy SVG/PNG frames beside MP4")
    args = parser.parse_args(argv)
    try:
        for executable in ("cargo", "rustc", "ffmpeg", "rsvg-convert"):
            if not shutil.which(executable):
                raise RuntimeError(f"missing dependency: {executable}")
        source = args.project.resolve(strict=True)
        output = args.output.resolve()
        if source.suffix.lower() != ".json":
            raise ValueError("project must be a .json file")
        if output.suffix.lower() != ".mp4":
            raise ValueError("output must be an .mp4 file")
        if output == source:
            raise ValueError("output must differ from project")
        spec = json.loads(source.read_text(encoding="utf-8"))
        fps, total = validate(spec)
        voice = audio_path(args.voiceover or spec.get("voiceover"), source)
        music = audio_path(args.music or spec.get("music"), source)
        output.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(prefix="ain-video-") as folder:
            frames = Path(folder)
            embedded = embed_images(spec, source)
            normalized = json.dumps(embedded, ensure_ascii=False, separators=(",", ":"))
            if len(normalized.encode("utf-8")) > 7_500_000:
                raise ValueError("Ain JSON payload exceeds 7.5 MB after embedding images")
            project_file = frames / "normalized.json"
            project_file.write_text(normalized, encoding="utf-8")
            environment = os.environ.copy()
            environment.update(AIN_VIDEO_SPEC=str(project_file), AIN_VIDEO_FRAMES=str(frames))
            command = ["cargo", "run", "--quiet", "--", "run", str(RENDERER)]
            result = subprocess.run(
                command, cwd=ROOT, env=environment,
                check=True, text=True, capture_output=True,
            )
            report = json.loads(result.stdout.splitlines()[-1])
            if not report.get("ok") or report.get("frames") != total:
                raise RuntimeError(f"Ain frame renderer failed: {report.get('error', 'incomplete frames')}")
            paths = [
                (frames / f"frame_{i:06d}.svg", frames / f"frame_{i:06d}.png")
                for i in range(total)
            ]
            if not all(svg.is_file() for svg, _ in paths):
                raise RuntimeError("Ain did not write every expected SVG frame")
            with ThreadPoolExecutor(max_workers=min(os.cpu_count() or 2, 8)) as pool:
                list(pool.map(rasterize, paths))
            encode_video(frames, output, fps, total, voice, music)
            if args.keep_frames:
                debug_dir = output.with_suffix(".frames")
                if debug_dir.exists():
                    raise ValueError(f"frame destination already exists: {debug_dir}")
                shutil.copytree(frames, debug_dir)
        print(f"Created {output} ({total} frames, {fps} fps)")
        return 0
    except (OSError, ValueError, RuntimeError, json.JSONDecodeError, subprocess.CalledProcessError) as error:
        print(f"video generation failed: {error}", file=sys.stderr)
        if isinstance(error, subprocess.CalledProcessError) and error.stderr:
            print(error.stderr, file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
